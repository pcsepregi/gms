function masterSheet(wb: ExcelJS.Workbook, rows: (Row | null)[], header = true) {
  const ws = wb.addWorksheet('MASTER SET');
  ws.getCell('A1').value = 'MASTER SET — SYNTHETIC TEST FIXTURE';
  ws.getCell('A2').value = 'Generated by scripts/make-fixtures.ts. Not real collection data.';
  const headerRow = ws.getRow(4);
  (header ? HEADERS : HEADERS.map((h) => (h === 'Have?' ? 'Owned' : h))).forEach((h, i) => {
    headerRow.getCell(i + 1).value = h;
  });
  rows.forEach((r, i) => {
    const excelRow = ws.getRow(5 + i);
    if (!r) return;
    r.forEach((v, c) => {
      const cell = excelRow.getCell(c + 1);
      if (c === 11 && typeof v === 'string' && v.startsWith('http')) {
        cell.value = { text: v, hyperlink: v };
      } else {
        cell.value = v;
      }
      if (c === 5 && typeof v === 'number') cell.numFmt = '000';
    });
  });
  return ws;
}

function dictionarySheet(wb: ExcelJS.Workbook) {
  const ws = wb.addWorksheet('VARIANT DICTIONARY');
  ws.addRow(['Standard Finish', 'Meaning']);
  DICTIONARY.forEach((d) => ws.addRow(d));
}

function dashboardSheet(wb: ExcelJS.Workbook) {
  const ws = wb.addWorksheet('COLLECTION DASHBOARD');
  ws.getCell('A1').value = 'SYNTHETIC DASHBOARD';
}

async function write(name: string, build: (wb: ExcelJS.Workbook) => void) {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'gms fixtures';
  wb.created = new Date('2026-01-01T00:00:00Z');
  wb.modified = wb.created;
  build(wb);
  const file = path.join(OUT, name);
  await wb.xlsx.writeFile(file);
  console.log(`írva: ${path.relative(process.cwd(), file)}`);
}

